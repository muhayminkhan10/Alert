// Precompute downstream mappings for fast blast-radius & topology queries
const DOWNSTREAM_MAP = new Map<string, string[]>();
SERVICES_TOPOLOGY.forEach(svc => {
  DOWNSTREAM_MAP.set(svc.id, []);
});

SERVICES_TOPOLOGY.forEach(sourceSvc => {
  sourceSvc.dependencies.forEach(depId => {
    const list = DOWNSTREAM_MAP.get(depId);
    if (list && !list.includes(sourceSvc.id)) {
      list.push(sourceSvc.id);
    }
  });
});

SERVICES_TOPOLOGY.forEach(svc => {
  svc.downstream = DOWNSTREAM_MAP.get(svc.id) || [];
});

export const SERVICE_MAP = new Map<string, ServiceNode>(
  SERVICES_TOPOLOGY.map(s => [s.id, s])
);

export function getService(id: string): ServiceNode | undefined {
  return SERVICE_MAP.get(id);
}

/**
 * Returns downstream services that can be impacted if rootService fails (Blast Radius)
 */
export function getDownstreamBlastRadius(serviceId: string, maxHops: number = 4): string[] {
  const visited = new Set<string>();
  const queue: { id: string; hops: number }[] = [{ id: serviceId, hops: 0 }];

  while (queue.length > 0) {
    const item = queue.shift()!;
    if (item.hops >= maxHops) continue;

    const downstreamList = DOWNSTREAM_MAP.get(item.id) || [];
    for (const downstreamId of downstreamList) {
      if (!visited.has(downstreamId) && downstreamId !== serviceId) {
        visited.add(downstreamId);
        queue.push({ id: downstreamId, hops: item.hops + 1 });
      }
    }
  }

  return Array.from(visited);
}

/**
 * Returns upstream services that this service depends on directly or transitively
 */
export function getUpstreamAncestors(serviceId: string, maxHops: number = 4): string[] {
  const visited = new Set<string>();
  const queue: { id: string; hops: number }[] = [{ id: serviceId, hops: 0 }];

  while (queue.length > 0) {
    const item = queue.shift()!;
    if (item.hops >= maxHops) continue;

    const svc = SERVICE_MAP.get(item.id);
    if (!svc) continue;

    for (const upstreamId of svc.dependencies) {
      if (!visited.has(upstreamId) && upstreamId !== serviceId) {
        visited.add(upstreamId);
        queue.push({ id: upstreamId, hops: item.hops + 1 });
      }
    }
  }

  return Array.from(visited);
}

/**
 * Precomputed All-Pairs Shortest Path Distance Matrix for 70 Microservices
 * Enables O(1) distance queries during high-throughput correlation.
 */
const TOPOLOGY_DIST_MAP = new Map<string, Map<string, number>>();

function precomputeAllPairsDistances() {
  const allIds = SERVICES_TOPOLOGY.map(s => s.id);

  for (const startId of allIds) {
    const dists = new Map<string, number>();
    dists.set(startId, 0);

    const visited = new Set<string>([startId]);
    const queue: { id: string; dist: number }[] = [{ id: startId, dist: 0 }];

    while (queue.length > 0) {
      const { id, dist } = queue.shift()!;
      if (dist >= 5) continue;

      const currentSvc = SERVICE_MAP.get(id);
      if (!currentSvc) continue;

      const neighbors = [...currentSvc.dependencies, ...(DOWNSTREAM_MAP.get(id) || [])];
      for (const n of neighbors) {
        if (!visited.has(n)) {
          visited.add(n);
          dists.set(n, dist + 1);
          queue.push({ id: n, dist: dist + 1 });
        }
      }
    }

    TOPOLOGY_DIST_MAP.set(startId, dists);
  }
}

precomputeAllPairsDistances();

/**
 * Computes shortest topological distance between two services (undirected connectivity).
 * Runs in O(1) time via precomputed distance matrix.
 */
export function getTopologyDistance(svcA: string, svcB: string): number {
  if (svcA === svcB) return 0;
  const fromMap = TOPOLOGY_DIST_MAP.get(svcA);
  if (!fromMap) return Infinity;
  const dist = fromMap.get(svcB);
  return dist !== undefined ? dist : Infinity;
}
